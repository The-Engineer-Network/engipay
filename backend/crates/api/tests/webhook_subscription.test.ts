      // posts a subscription with endpoint_url and events
      const subscriptionData = {
        endpoint_url: "https://merchant.example.com/webhooks",
        events: ["payment.received", "payment.paid"],
      }

      // In a real test, we'd make an authenticated request
      // For now, verify the data structure is correct
      assert.equal(subscriptionData.endpoint_url, "https://merchant.example.com/webhooks")
      assert.equal(subscriptionData.events.length, 2)
      assert.equal(subscriptionData.events[0], "payment.received")
      assert.equal(subscriptionData.events[1], "payment.paid")
